"""Small dependency-free parser for Russian channel numbers."""

UNITS = {
    "ноль": 0,
    "один": 1, "одна": 1, "первый": 1, "первого": 1,
    "два": 2, "две": 2, "второй": 2, "второго": 2,
    "три": 3, "третий": 3, "третьего": 3,
    "четыре": 4, "четвертый": 4, "четвёртый": 4,
    "пять": 5, "пятый": 5,
    "шесть": 6, "шестой": 6,
    "семь": 7, "седьмой": 7,
    "восемь": 8, "восьмой": 8,
    "девять": 9, "девятый": 9,
}

TEENS = {
    "десять": 10, "десятый": 10,
    "одиннадцать": 11, "одиннадцатый": 11,
    "двенадцать": 12, "двенадцатый": 12,
    "тринадцать": 13, "тринадцатый": 13,
    "четырнадцать": 14, "четырнадцатый": 14,
    "пятнадцать": 15, "пятнадцатый": 15,
    "шестнадцать": 16, "шестнадцатый": 16,
    "семнадцать": 17, "семнадцатый": 17,
    "восемнадцать": 18, "восемнадцатый": 18,
    "девятнадцать": 19, "девятнадцатый": 19,
}

TENS = {
    "двадцать": 20, "двадцатый": 20,
    "тридцать": 30, "тридцатый": 30,
    "сорок": 40, "сороковой": 40,
    "пятьдесят": 50, "пятидесятый": 50,
    "шестьдесят": 60, "шестидесятый": 60,
    "семьдесят": 70, "семидесятый": 70,
    "восемьдесят": 80, "восьмидесятый": 80,
    "девяносто": 90, "девяностый": 90,
}

HUNDREDS = {
    "сто": 100, "сотый": 100,
    "двести": 200, "двухсотый": 200,
    "триста": 300, "трехсотый": 300, "трёхсотый": 300,
    "четыреста": 400, "четырехсотый": 400, "четырёхсотый": 400,
    "пятьсот": 500, "пятисотый": 500,
    "шестьсот": 600, "шестисотый": 600,
    "семьсот": 700, "семисотый": 700,
    "восемьсот": 800, "восьмисотый": 800,
    "девятьсот": 900, "девятисотый": 900,
}


def parse_spoken_number(text):
    """Convert Russian cardinal/ordinal channel words to an integer."""
    words = (
        text.lower()
        .replace("ё", "е")
        .replace("-", " ")
        .replace("телеканал", " ")
        .replace("канал", " ")
        .split()
    )
    if not words:
        return None

    total = 0
    matched = False
    dictionaries = (HUNDREDS, TENS, TEENS, UNITS)
    for word in words:
        if word.isdigit():
            total += int(word)
            matched = True
            continue
        for values in dictionaries:
            if word in values:
                total += values[word]
                matched = True
                break
        else:
            return None
    return total if matched else None
